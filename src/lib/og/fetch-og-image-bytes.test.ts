import { describe, expect, it } from "vitest";

import { bytesToOgImageDataUri } from "@/lib/og/fetch-og-image-bytes";

/** Minimal valid PNG (1×1). */
const TINY_PNG = Uint8Array.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49,
  0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06,
  0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00, 0x00, 0x00, 0x0a, 0x49, 0x44,
  0x41, 0x54, 0x78, 0x9c, 0x63, 0x00, 0x01, 0x00, 0x00, 0x05, 0x00, 0x01, 0x0d,
  0x0a, 0x2d, 0xb4, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42,
  0x60, 0x82,
]);

describe("bytesToOgImageDataUri", () => {
  it("returns a PNG data URI for PNG bytes", () => {
    const result = bytesToOgImageDataUri(TINY_PNG);
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.dataUri.startsWith("data:image/png;base64,")).toBe(true);
      expect(result.mimeType).toBe("image/png");
    }
  });

  it("rejects empty bytes", () => {
    expect(bytesToOgImageDataUri(new Uint8Array())).toMatchObject({
      ok: false,
      reason: "empty",
    });
  });
});
