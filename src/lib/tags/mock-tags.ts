export function getMockTagScan(uuid: string): TagScanResult | null {
  const tag = mockTags[uuid];
  if (!tag) return null;

  if (tag.status === "active" && tag.vehicle_id === mockVehicle.id) {
    return {
      tag,
      vehicle: mockVehicle,
      documents: mockDocuments,
    };
  }

  return {
    tag,
    vehicle: null,
    documents: [],
  };
}
